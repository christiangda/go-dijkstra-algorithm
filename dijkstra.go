// Package dijkstra is a library implementation Dijkstra's algorithm.
//
// Dijkstra's algorithm (created by Edsger W. Dijkstra in 1956) solves the shortest path problem from a single source node to all other nodes in a weighted graph with non-negative weights (>= 0).
package dijkstra

import (
	"container/heap"
	"math"
	"slices"
)

// Edge represent each edge in the Graph
type Edge struct {
	// to is the destination node id
	to int

	// weight always should be greater or equal to zero, never negative
	// since Dijkstra's Algorithm does not support negative distances
	weight float64
}

// Graph is represented for each Node id and the slice of adjacent edges
type Graph [][]Edge

func (g Graph) Len() int {
	return len(g)
}

// Forces a compile-time check that *PriorityQueue satisfies heap.Interface using the datatype we need for the Edge (to, weight)
// this is just a compile check, it is and very good additional check
var _ heap.Interface = (*PriorityQueue[int, float64])(nil)

func DijkstraShortestPath(g Graph, startNode, targetNode int) (distances []float64, previous []int) {
	if startNode == targetNode {
		return []float64{0}, []int{startNode}
	}

	graphLength := g.Len()
	distances = make([]float64, graphLength)
	previous = make([]int, graphLength)

	if startNode < 0 || startNode >= graphLength {
		return distances, previous
	}

	// initialize distances with infinite (math.Inf) and previous with -1
	for i := range graphLength {
		distances[i] = math.Inf(1)
		previous[i] = -1
	}

	distances[startNode] = 0.0

	pq := &PriorityQueue[int, float64]{}
	heap.Init(pq)
	heap.Push(pq, &Item[int, float64]{value: startNode, priority: 0.0})

	for pq.Len() > 0 {
		currentItem := heap.Pop(pq).(*Item[int, float64])
		currentNode := currentItem.value
		currentDist := currentItem.priority

		// Lazy Deletion: if we found an obsolete item in the heap, we ignore it
		if currentDist > distances[currentNode] {
			continue
		}

		// Early Exit: if we arrive to target, we finished
		if currentNode == targetNode {
			break
		}

		for _, edge := range g[currentNode] {
			nextNode := edge.to
			weight := edge.weight

			if nextNode < 0 || nextNode >= graphLength {
				continue
			}

			newDistance := distances[currentNode] + weight

			if newDistance < distances[nextNode] {
				distances[nextNode] = newDistance
				previous[nextNode] = currentNode
				heap.Push(pq, &Item[int, float64]{value: nextNode, priority: newDistance})
			}
		}
	}

	return distances, previous
}

// ReconstructPath use the previous generated by DijkstraShortestPath
// and together with the startNode and the targetNode return the right path from startNode to targetNode
func ReconstructPath(previous []int, startNode, targetNode int) (path []int) {
	if targetNode < 0 || targetNode >= len(previous) {
		return nil
	}

	// if the targetNode if not reachable and it is not startNode
	if previous[targetNode] == -1 && targetNode != startNode {
		return nil
	}

	path = make([]int, len(previous))
	curr := targetNode

	// we traverse in reverse using the`previous` slice
	for curr != -1 {
		path = append(path, curr)
		if curr == startNode {
			break
		}

		curr = previous[curr]
	}

	// are we in the startNode?
	if len(path) == 0 || path[len(path)-1] != startNode {
		return nil // there is not valid path
	}

	slices.Reverse(path)

	return path
}
